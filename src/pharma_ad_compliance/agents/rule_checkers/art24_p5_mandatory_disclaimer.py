"""ст. 24 ч. 7 — обязательное предупреждение о противопоказаниях.

Стандартные формулировки:
- ЛС: "Имеются противопоказания, проконсультируйтесь со специалистом".
- Медуслуги/медизделия: "Имеются противопоказания, проконсультируйтесь с врачом".

Это "absence-based" правило — нарушение есть тогда, когда формулировка ОТСУТСТВУЕТ
(или искажена, или замаскирована мелким шрифтом — последнее по тексту мы не увидим,
поэтому ловим только полное отсутствие/искажение).
"""
from __future__ import annotations

from ...schemas import DrugClass, ParsedCreative, RuleId, Violation
from ._base import check_rule

RULE_ID = RuleId.ART24_P5_MANDATORY_DISCLAIMER

FOCUS = """\
Признаки нарушения:
- В тексте полностью отсутствует фраза о противопоказаниях/консультации.
- Использована искажённая формулировка ("обратитесь к врачу при необходимости" — этого
  недостаточно: ФАС требует именно указание на ПРОТИВОПОКАЗАНИЯ).
- Дисклеймер есть, но не упоминает консультацию со специалистом/врачом.

Допустимые формулировки (любая считается соответствующей):
- "Имеются противопоказания, проконсультируйтесь со специалистом"
- "Имеются противопоказания, проконсультируйтесь с врачом"
- "Имеются противопоказания. Перед применением проконсультируйтесь со специалистом"

Если дисклеймер ОТСУТСТВУЕТ — это CRITICAL. quote=null.
Если формулировка искажена — WARNING с цитатой искажённой версии.

ВАЖНО: правило неприменимо для категории BAD (для БАД требования другой статьи).
Для UNKNOWN — флагировать как WARNING, оставив комментарий "категория не определена".
"""


async def check(
    parsed: ParsedCreative,
    drug_class: DrugClass,
    *,
    user_feedback: list[str] | None = None,
) -> list[Violation]:
    if drug_class == DrugClass.BAD:
        return []
    return await check_rule(
        parsed=parsed,
        drug_class=drug_class,
        rule_id=RULE_ID,
        focus_instruction=FOCUS,
        user_feedback=user_feedback,
    )

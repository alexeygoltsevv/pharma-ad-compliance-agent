"""ст. 24 ч. 1 п. 1 — реклама ЛС не должна обращаться к несовершеннолетним."""
from __future__ import annotations

from ...schemas import DrugClass, ParsedCreative, RuleId, Violation
from ._base import check_rule

RULE_ID = RuleId.ART24_P1_MINORS

FOCUS = """\
Признаки нарушения:
- Прямое обращение к детям/подросткам ("ребята", "школьники", "детям", "подросткам").
- Использование детских образов как целевой аудитории сообщения.
- Призывы родителям "купите ребёнку", если в самом сообщении адресат — ребёнок.
- Игровая лексика, апеллирующая к детской аудитории.
Не путать с указанием возрастной группы применения препарата (это допустимо, если
оформлено как мед-информация, а не как обращение).

Ключевое разграничение:
- Если ребёнок — ПАЦИЕНТ (изображён как тот, кому препарат назначен), а
  сообщение адресовано РОДИТЕЛЮ — это НЕ нарушение п. 1.
- Если же риторика прямо обращена к ребёнку как к покупателю или принимающему
  решение («ребята, попроси маму купить», «школьники, держите в портфеле») —
  это нарушение п. 1.
- Если ребёнок присутствует в кадре, но обращение в тексте — на «вы», к
  взрослому потребителю — это НЕ нарушение.

Тест: можно ли заменить слово «ребёнок» на «больной» без потери смысла? Если
да — это медицинское описание, не обращение к несовершеннолетним.
"""


async def check(
    parsed: ParsedCreative,
    drug_class: DrugClass,
    *,
    user_feedback: list[str] | None = None,
) -> list[Violation]:
    return await check_rule(
        parsed=parsed,
        drug_class=drug_class,
        rule_id=RULE_ID,
        focus_instruction=FOCUS,
        user_feedback=user_feedback,
    )

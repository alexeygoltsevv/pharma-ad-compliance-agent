"""Прочие подпункты ст. 24 — все, не закрытые специализированными чекерами выше.

Сюда попадают:
- ч. 1 п. 3 — выражение благодарности от потребителей.
- ч. 1 п. 4 — упоминание процесса/факта обязательных регистрационных
  исследований как преимущества (буквальный текст п. 4; вынесен сюда из
  ART24_P4_DOCTOR_RECOMMENDATION, который теперь покрывает только ложные
  экспертные рекомендации).
- ч. 1 п. 5 — утверждения о наличии у потребителей заболеваний.
- ч. 1 п. 6 — впечатление о необходимости применения у здорового человека.
- ч. 1 п. 7 — впечатление ненужности обращения к врачу.
- ч. 1 п. 9 — представление БАД в виде ЛС (и наоборот).
- ч. 1 п. 10 — гарантия безопасности через "естественное происхождение".

Этот чекер служит safety-net'ом: ловит то, что специализированные пропустили.
"""
from __future__ import annotations

from ...schemas import DrugClass, ParsedCreative, RuleId, Violation
from ._base import check_rule

RULE_ID = RuleId.ART24_OTHER

FOCUS = """\
Проверь, не нарушены ли подпункты ст. 24 ч. 1, НЕ покрытые отдельными чекерами:

- п. 3: благодарность потребителей за результат лечения.
- п. 4: упоминание процесса/факта государственной регистрации препарата или
  обязательных регистрационных исследований как преимущества («прошёл все
  испытания», «зарегистрирован Минздравом», «препарат с регистрационным
  удостоверением» — как маркетинговый аргумент). См. дело «Артра», 2024.
- п. 5: "наверняка у вас есть [заболевание]" — навязывание диагноза,
  провокация тревоги о болезни.
- п. 6: "каждому здоровому человеку нужно принимать X для профилактики".
- п. 7: "не нужно идти к врачу, просто примите X".
- п. 9: реклама БАД представляет его как лекарственное средство (или наоборот);
  для БАД — отсутствие обязательной пометки «не является лекарственным средством».
- п. 10: безопасность гарантирована "натуральным составом".

Severity-калибровка для этого чекера (ст. 24 ч. 1, подпункты, не покрытые
отдельными чекерами):
- п. 3 (благодарность от пациента): WARNING (если без диагноза) / CRITICAL
  (с описанием диагноза).
- п. 4 (упоминание регистрационных исследований как преимущества): CRITICAL —
  см. дело «Артра», 2024.
- п. 5 (навязывание диагноза, провокация тревоги о болезни): CRITICAL — даже
  без явной гарантии, см. практику по «Артра», 2024.
- п. 6 (впечатление о необходимости применения у здорового): WARNING.
- п. 7 (впечатление о ненужности обращения к врачу): CRITICAL.
- п. 9 (БАД представлен как ЛС или наоборот): CRITICAL — отдельная статья
  нарушения.
- п. 10 (безопасность через «естественное происхождение»): CRITICAL —
  повторяющийся паттерн, см. «Настойка сабельника», 2023.

В поле `explanation` ОБЯЗАТЕЛЬНО укажи конкретный подпункт ст. 24 ч. 1, по
которому квалифицируешь нарушение.

Дополнительно — если drug_class=BAD и в креативе нет пометки «не является
лекарственным средством» — флагируй как CRITICAL с rule_id ART24_OTHER и
подпункт п. 9 (см. дело Яндекс/Эдифарм, 2023).
"""


async def check(
    parsed: ParsedCreative,
    drug_class: DrugClass,
    *,
    user_feedback: list[str] | None = None,
) -> list[Violation]:
    return await check_rule(
        parsed=parsed,
        drug_class=drug_class,
        rule_id=RULE_ID,
        focus_instruction=FOCUS,
        user_feedback=user_feedback,
    )

"""Чекер «ложная экспертная рекомендация» — врач/фармацевт/иной медработник.

Misleading historical name: this checker covers pseudo-expert endorsements
(врач/фармацевт/актёр в халате, «врачи рекомендуют» и т. п.), which follows
from совокупное прочтение ч. 1 п. 4 и ст. 5 ФЗ-38. Буквальный п. 4
(«создание представления о преимуществах путём ссылки на факт исследований,
обязательных для государственной регистрации») вынесен в `art24_other.py`,
потому что он по природе — отдельная категория нарушений.

Имя `RuleId.ART24_P4_DOCTOR_RECOMMENDATION` сохраняется по совместимости
со схемой (переименование = breaking change для отчётов и dataset'ов).

ФАС многократно штрафовала за рекламу, где актёр в халате представлен как врач
или фармацевт и даёт рекомендацию. Допустимо ТОЛЬКО если в кадре реальный врач,
имеющий право давать такую рекомендацию, с раскрытием его данных.
"""
from __future__ import annotations

from ...schemas import DrugClass, ParsedCreative, RuleId, Violation
from ._base import check_rule

RULE_ID = RuleId.ART24_P4_DOCTOR_RECOMMENDATION

FOCUS = """\
Проверь, нет ли в креативе ложной экспертной рекомендации — врача, фармацевта
или иного медработника (включая роль актёра в халате).

Признаки нарушения:
- Персонаж представлен как "врач", "фармацевт", "провизор" и даёт рекомендацию
  при отсутствии явного указания, что это реальный специалист.
- Изображение белого халата + рекомендации препарата без указания лица.
- "Врачи рекомендуют X" без ссылки на конкретное исследование/сертификат.
- "Фармацевт советует" — типичный паттерн нарушения.

Допустимо: цитата реального врача с ФИО, специализацией и местом работы; ссылка на
конкретное клиническое исследование с указанием источника.

Важно: буквальный ч. 1 п. 4 («ссылка на факт государственной регистрации /
обязательных регистрационных исследований как преимущество») проверяется
отдельным чекером (`ART24_OTHER`) — НЕ дублируй сюда.
"""


async def check(
    parsed: ParsedCreative,
    drug_class: DrugClass,
    *,
    user_feedback: list[str] | None = None,
) -> list[Violation]:
    return await check_rule(
        parsed=parsed,
        drug_class=drug_class,
        rule_id=RULE_ID,
        focus_instruction=FOCUS,
        user_feedback=user_feedback,
    )
